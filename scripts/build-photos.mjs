import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const root = process.cwd()
const manifestPath = path.join(root, 'photos/manifest.json')
const sourceRoot = path.join(root, 'photos/originals')
const outputRoot = path.join(root, 'public/images/generated')
const legacyOutputRoot = path.join(root, 'public/images/portfolio')
const generatedDataPath = path.join(root, 'src/data/photos.generated.ts')
const targetWidths = [480, 768, 1200, 1800, 2400]
const gallerySlugs = new Set([
  'travel-landscape',
  'architecture-spaces',
  'fine-art',
  'people-moments',
])

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))

if (!Array.isArray(manifest.photos)) {
  throw new Error('photos/manifest.json must contain a "photos" array.')
}

const ids = new Set()
const heroPhotos = manifest.photos.filter((photo) => photo.hero)
const portraitPhotos = manifest.photos.filter((photo) => photo.portrait)

if (heroPhotos.length !== 1) {
  throw new Error(`Exactly one manifest photograph must set "hero": true; found ${heroPhotos.length}.`)
}
if (portraitPhotos.length !== 1) {
  throw new Error(`Exactly one manifest photograph must set "portrait": true; found ${portraitPhotos.length}.`)
}

await rm(outputRoot, { recursive: true, force: true })
await rm(legacyOutputRoot, { recursive: true, force: true })
await mkdir(outputRoot, { recursive: true })

const generatedPhotos = []

for (const [index, photo] of manifest.photos.entries()) {
  const label = photo.id || `entry ${index + 1}`

  if (!/^[a-z0-9][a-z0-9-]*$/.test(photo.id ?? '')) {
    throw new Error(`${label}: "id" must use lowercase letters, numbers, and hyphens only.`)
  }
  if (ids.has(photo.id)) throw new Error(`${label}: duplicate photo id.`)
  ids.add(photo.id)

  for (const field of ['source', 'title', 'description']) {
    if (typeof photo[field] !== 'string' || !photo[field].trim()) {
      throw new Error(`${label}: "${field}" is required.`)
    }
  }
  if (!Array.isArray(photo.galleries) || photo.galleries.length === 0) {
    throw new Error(`${label}: add at least one gallery placement.`)
  }

  const galleryNames = new Set()
  for (const placement of photo.galleries) {
    if (!gallerySlugs.has(placement.slug)) {
      throw new Error(`${label}: unknown gallery "${placement.slug}".`)
    }
    if (galleryNames.has(placement.slug)) {
      throw new Error(`${label}: gallery "${placement.slug}" is listed more than once.`)
    }
    if (!Number.isFinite(placement.order)) {
      throw new Error(`${label}: gallery order must be a number.`)
    }
    galleryNames.add(placement.slug)
  }

  const sourcePath = path.resolve(sourceRoot, photo.source)
  if (!sourcePath.startsWith(`${sourceRoot}${path.sep}`)) {
    throw new Error(`${label}: source must stay inside photos/originals/.`)
  }

  const image = sharp(sourcePath, { failOn: 'none' }).rotate()
  const metadata = await image.metadata()
  const oriented = metadata.autoOrient ?? metadata

  if (!oriented.width || !oriented.height) {
    throw new Error(`${label}: unable to read image dimensions.`)
  }

  const largestWidth = Math.min(oriented.width, targetWidths.at(-1))
  const widths = [...new Set([
    ...targetWidths.filter((width) => width < largestWidth),
    largestWidth,
  ])].sort((a, b) => a - b)

  const variants = []
  for (const width of widths) {
    const filename = `${photo.id}-${width}.webp`
    await image
      .clone()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: width <= 768 ? 80 : 84, effort: 5 })
      .toFile(path.join(outputRoot, filename))

    variants.push({
      width,
      src: `/images/generated/${filename}`,
    })
  }

  const largest = variants.at(-1)
  generatedPhotos.push({
    ...photo,
    width: oriented.width,
    height: oriented.height,
    aspectRatio: `${oriented.width}/${oriented.height}`,
    src: largest.src,
    thumbnailSrc: variants[0].src,
    srcSet: variants.map((variant) => `${variant.src} ${variant.width}w`).join(', '),
  })
}

const generatedSource = `// Generated by scripts/build-photos.mjs. Do not edit manually.
export const generatedPhotos = ${JSON.stringify(generatedPhotos, null, 2)} as const
`

await writeFile(generatedDataPath, generatedSource)
console.log(
  `Generated ${generatedPhotos.length} photographs and removed obsolete output files.`,
)
